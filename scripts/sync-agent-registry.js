#!/usr/bin/env node
// Vendors the canonical Crowe agent registry into rooms/agents.vendored.json.
//
//   node scripts/sync-agent-registry.js [path-to-crowe-agents]
//
// Why a vendored snapshot rather than reading the sibling repo at runtime: the
// desktop app ships to machines that do not have ~/crowe-agents checked out,
// and a room whose roster is empty because a sibling repo is missing is a
// broken product, not a degraded one. The snapshot is the shipped truth; this
// script is how it is refreshed, and it is reviewed like any other source.
//
// The registry stays the single source. Rooms needs three facts it does not
// carry, and they are DERIVED here rather than authored per agent, so the two
// files cannot drift into disagreeing about the same agent:
//
//   model            per-agent deployment override, read from the registry's own
//                    model_roles. Absent when the registry does not state one,
//                    so the agent inherits the room default instead of a guess.
//   autonomyCeiling  mapped from `authority`, which already governs tool access
//                    upstream. advisory has no tools at all, so it caps at plan.
//   roomJoinable     whether the agent may be composed into a room. Everything
//                    in the registry is today; the flag exists so upstream can
//                    retire one from rooms without deleting the agent.
//
// scripts/test-rooms.js asserts this file matches the upstream registry when
// the sibling repo is present, and skips that check when it is not.

const fs = require("fs");
const path = require("path");

// authority is the registry's own vocabulary for what an agent may touch.
// Mapping it to the app's autonomy tiers keeps one permission story rather than
// two: an agent cannot be granted a room seat more powerful than the registry
// already says it should hold.
const CEILING = { advisory: "plan", read_only: "readonly", read_confirm: "edit" };

function vendor(registryJsonPath) {
  const src = JSON.parse(fs.readFileSync(registryJsonPath, "utf8"));
  const defaults = src.defaults || {};
  const agents = (src.agents || []).map((raw) => {
    const m = { ...defaults, ...raw };
    const model = (m.model_roles && (m.model_roles.ORCHESTRATOR || m.model_roles.WORKER_CONSIDERED)) || "";
    return {
      id: m.id,
      name: m.name,
      domain: m.domain || "",
      role: m.role || "",
      authority: m.authority || "advisory",
      autonomyCeiling: CEILING[m.authority || "advisory"] || "plan",
      roomJoinable: m.room_joinable !== false,
      ...(m.model || model ? { model: m.model || model } : {}),
      tools: Array.isArray(m.tools) ? m.tools : [],
      systemPrompt: String(m.system_prompt || "").replace(/\s+/g, " ").trim(),
    };
  });
  return {
    version: src.version,
    generatedFrom: "michaelcrowe11/crowe-agents registry/agents.json",
    sourceVersion: src.version,
    note: "GENERATED by scripts/sync-agent-registry.js. Do not edit by hand. Vendored snapshot of the canonical Crowe agent registry, with the three additive Rooms fields (model, autonomyCeiling, roomJoinable) derived from the registry's own authority vocabulary.",
    agents,
  };
}

module.exports = { vendor, CEILING };

if (require.main === module) {
  const root = process.argv[2] || path.join(process.env.HOME || "", "crowe-agents");
  const reg = path.join(root, "registry", "agents.json");
  if (!fs.existsSync(reg)) {
    console.error(`no registry at ${reg}\npass the crowe-agents checkout as argv[2]`);
    process.exit(1);
  }
  const out = vendor(reg);
  const dest = path.join(__dirname, "..", "rooms", "agents.vendored.json");
  fs.writeFileSync(dest, JSON.stringify(out, null, 2) + "\n");
  console.log(`wrote ${path.relative(path.join(__dirname, ".."), dest)}: ${out.agents.length} agents from registry ${out.sourceVersion}`);
}
